-- ProofMesh Dynamic Multi-Agent Swarm Database Schema for Supabase
-- Autonomous AI Research Scientist

-- 1. Research Sessions
CREATE TABLE IF NOT EXISTS research_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID,
    query TEXT NOT NULL,
    depth TEXT NOT NULL DEFAULT 'standard' CHECK (depth IN ('quick', 'standard', 'deep')),
    status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'planning', 'dispatching', 'running', 'aggregating', 'analyzing', 'verifying', 'reporting', 'completed', 'partially_completed', 'failed', 'cancelled')),
    executive_summary TEXT,
    methodology TEXT,
    total_objectives INT NOT NULL DEFAULT 0,
    completed_objectives INT NOT NULL DEFAULT 0,
    total_agents INT NOT NULL DEFAULT 0,
    active_agents INT NOT NULL DEFAULT 0,
    total_website_tasks INT NOT NULL DEFAULT 0,
    completed_website_tasks INT NOT NULL DEFAULT 0,
    failed_website_tasks INT NOT NULL DEFAULT 0,
    sources_discovered INT NOT NULL DEFAULT 0,
    claims_extracted INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    metadata JSONB DEFAULT '{}'::jsonb
);

-- 2. Research Objectives (Dynamically generated by Master Planner)
CREATE TABLE IF NOT EXISTS research_objectives (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    parent_objective_id UUID REFERENCES research_objectives(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    specialization TEXT NOT NULL,
    priority INT NOT NULL DEFAULT 1,
    dependencies JSONB DEFAULT '[]'::jsonb,
    search_queries JSONB DEFAULT '[]'::jsonb,
    preferred_source_types JSONB DEFAULT '[]'::jsonb,
    geographical_scope TEXT,
    temporal_scope TEXT,
    expected_evidence TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'running', 'completed', 'partially_completed', 'failed', 'skipped')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Research Agents (Dynamically instantiated per objective/specialization)
CREATE TABLE IF NOT EXISTS research_agents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    objective_id UUID REFERENCES research_objectives(id) ON DELETE SET NULL,
    specialization TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    status TEXT NOT NULL DEFAULT 'idle' CHECK (status IN ('idle', 'running', 'completed', 'partially_completed', 'failed', 'cancelled')),
    task_id TEXT,
    progress INT NOT NULL DEFAULT 0,
    websites_dispatched INT NOT NULL DEFAULT 0,
    websites_succeeded INT NOT NULL DEFAULT 0,
    websites_failed INT NOT NULL DEFAULT 0,
    sources_found INT NOT NULL DEFAULT 0,
    claims_extracted INT NOT NULL DEFAULT 0,
    error TEXT,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    metadata JSONB DEFAULT '{}'::jsonb
);

-- 4. Website Tasks (Independent Level 3 execution)
CREATE TABLE IF NOT EXISTS website_tasks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    agent_id UUID NOT NULL REFERENCES research_agents(id) ON DELETE CASCADE,
    objective_id UUID REFERENCES research_objectives(id) ON DELETE SET NULL,
    url TEXT NOT NULL,
    goal TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'succeeded', 'partially_succeeded', 'failed', 'timed_out', 'skipped', 'cancelled')),
    retry_count INT NOT NULL DEFAULT 0,
    max_retries INT NOT NULL DEFAULT 2,
    execution_duration_ms INT,
    error_message TEXT,
    error_type TEXT,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    raw_result JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Sources
CREATE TABLE IF NOT EXISTS sources (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    agent_id UUID REFERENCES research_agents(id) ON DELETE SET NULL,
    website_task_id UUID REFERENCES website_tasks(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    url TEXT NOT NULL,
    domain TEXT NOT NULL,
    source_type TEXT NOT NULL DEFAULT 'web',
    publication_date TEXT,
    retrieved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    credibility_assessment JSONB DEFAULT '{}'::jsonb,
    content_snippet TEXT,
    verification_status TEXT NOT NULL DEFAULT 'verified' CHECK (verification_status IN ('verified', 'unverified', 'flagged'))
);

-- 6. Claims
CREATE TABLE IF NOT EXISTS claims (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    objective_id UUID REFERENCES research_objectives(id) ON DELETE SET NULL,
    source_id UUID NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    agent_id UUID REFERENCES research_agents(id) ON DELETE SET NULL,
    claim_text TEXT NOT NULL,
    original_passage TEXT NOT NULL,
    stance TEXT NOT NULL DEFAULT 'neutral' CHECK (stance IN ('supports', 'contradicts', 'neutral')),
    evidence_type TEXT NOT NULL DEFAULT 'empirical',
    confidence NUMERIC(4, 3) NOT NULL DEFAULT 0.850 CHECK (confidence >= 0.0 AND confidence <= 1.0),
    confidence_rationale TEXT,
    is_direct_evidence BOOLEAN NOT NULL DEFAULT true,
    verification_status TEXT NOT NULL DEFAULT 'verified' CHECK (verification_status IN ('verified', 'unverified', 'disputed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Contradictions
CREATE TABLE IF NOT EXISTS contradictions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    claim_a_id UUID NOT NULL REFERENCES claims(id) ON DELETE CASCADE,
    claim_b_id UUID NOT NULL REFERENCES claims(id) ON DELETE CASCADE,
    explanation TEXT NOT NULL,
    contradiction_type TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'medium' CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    resolution_status TEXT NOT NULL DEFAULT 'unresolved' CHECK (resolution_status IN ('unresolved', 'resolved_temporal', 'resolved_geographical', 'inconclusive', 'verified')),
    adaptive_verification_dispatched BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Evidence Graph Nodes
CREATE TABLE IF NOT EXISTS evidence_nodes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    node_type TEXT NOT NULL CHECK (node_type IN ('root_hypothesis', 'objective', 'sub_hypothesis', 'evidence', 'source', 'contradiction', 'verification')),
    reference_id UUID,
    label TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    position_x NUMERIC DEFAULT 0,
    position_y NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. Evidence Graph Edges
CREATE TABLE IF NOT EXISTS evidence_edges (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    source_node_id UUID NOT NULL REFERENCES evidence_nodes(id) ON DELETE CASCADE,
    target_node_id UUID NOT NULL REFERENCES evidence_nodes(id) ON DELETE CASCADE,
    relationship_type TEXT NOT NULL CHECK (relationship_type IN ('SUPPORTS', 'CONTRADICTS', 'DERIVED_FROM', 'REFERENCES', 'RELATED_TO', 'VERIFIES')),
    label TEXT,
    confidence NUMERIC(4, 3) DEFAULT 1.0,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. Research Reports
CREATE TABLE IF NOT EXISTS research_reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE UNIQUE,
    executive_summary TEXT NOT NULL,
    content_markdown TEXT NOT NULL,
    sections JSONB NOT NULL DEFAULT '[]'::jsonb,
    coverage_status TEXT NOT NULL DEFAULT 'complete',
    format TEXT NOT NULL DEFAULT 'markdown',
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 11. Research Events
CREATE TABLE IF NOT EXISTS research_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    research_id UUID NOT NULL REFERENCES research_sessions(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    stage TEXT,
    message TEXT NOT NULL,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_sessions_status ON research_sessions(status);
CREATE INDEX IF NOT EXISTS idx_objectives_research ON research_objectives(research_id);
CREATE INDEX IF NOT EXISTS idx_agents_research ON research_agents(research_id);
CREATE INDEX IF NOT EXISTS idx_tasks_agent ON website_tasks(agent_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON website_tasks(status);
CREATE INDEX IF NOT EXISTS idx_sources_research ON sources(research_id);
CREATE INDEX IF NOT EXISTS idx_claims_research ON claims(research_id);
CREATE INDEX IF NOT EXISTS idx_contradictions_research ON contradictions(research_id);
CREATE INDEX IF NOT EXISTS idx_nodes_research ON evidence_nodes(research_id);
CREATE INDEX IF NOT EXISTS idx_edges_research ON evidence_edges(research_id);
CREATE INDEX IF NOT EXISTS idx_events_research ON research_events(research_id, created_at);

